import assert from 'node:assert/strict';
import { classifyArchiveFailure as c, overloadedMessage as m, structuredArchiveWaitMessage as w } from './src/utils/archiveFailure.ts';
assert.equal(c(502, { upstreamStatus: 504, attempts: 3 }), 'overloaded');
assert.equal(c(502, { upstreamStatus: 500 }), 'overloaded');
assert.equal(c(502, { upstreamStatus: 0, attempts: 3 }), 'overloaded', 'no answer after 3 attempts');
assert.equal(c(502, { upstreamStatus: 0, attempts: 1 }), 'transient');
assert.equal(c(502, {}), 'transient');
assert.equal(c(502, { upstreamStatus: 404 }), 'definite'); assert.equal(c(403, { upstreamStatus: 403 }), 'definite');
assert.equal(c(422, { reason: 'UNPLAYABLE_ARCHIVE_MEMBER' }), 'definite'); assert.equal(c(400, {}), 'definite');
assert.equal(c(502, { upstreamStatus: 503 }), 'transient', '503 keeps the existing path');
assert.match(m({ upstreamStatus: 504 }), /Archive upstream returned HTTP 504/);
assert.match(m({ proxyHttpStatus: 504 }), /AJN proxy returned HTTP 504; the upstream cause was not recorded/);
assert.match(m({ errorCode: 'AJN_PROXY_HEADER_BUDGET_EXHAUSTED' }), /60 s total response-header wait budget/);
assert.match(w({ errorCode: 'AJN_UPSTREAM_HEADER_TIMEOUT' }), /Archive upstream response headers timed out/);
assert.match(w({ errorCode: 'AJN_UPSTREAM_CIRCUIT_OPEN', retryAfterSeconds: 12 }), /AJN proxy circuit open; retry in about 12 s/);
assert.doesNotMatch(m({}), /HTTP/);
assert.equal(c(503, { errorCode: 'AJN_UPSTREAM_CIRCUIT_OPEN', retryAfterSeconds: 12 }), 'slow', 'our own storage-host pause waits once, then retries');
assert.equal(c(504, { errorCode: 'AJN_UPSTREAM_HEADER_TIMEOUT' }), 'slow');
assert.equal(c(504, { errorCode: 'UND_ERR_CONNECT_TIMEOUT' }), 'slow');
assert.equal(c(504, { errorCode: 'AJN_PROXY_HEADER_BUDGET_EXHAUSTED' }), 'slow');
assert.equal(c(504, {}), 'overloaded', 'proxy 504 with no code still counts as overloaded');
console.log('archive failure: all passed');
