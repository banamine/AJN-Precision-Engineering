assert.equal(c(422, { reason: 'UNPLAYABLE_ARCHIVE_MEMBER' }), 'definite'); assert.equal(c(400, {}), 'definite');
assert.equal(c(502, { upstreamStatus: 503 }), 'transient', '503 keeps the existing path');
