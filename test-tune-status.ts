import assert from 'node:assert/strict';
import fs from 'node:fs';
import { nextTuneStatus, TuneStatus } from './src/utils/tuneStatus';
const s1 = nextTuneStatus({ kind: 'idle' }, { type: 'tune', label: 'Classic Rock 109' });
assert.deepEqual(s1, { kind: 'tuning', label: 'Classic Rock 109' });
assert.deepEqual(nextTuneStatus(s1, { type: 'playing' }), { kind: 'playing', label: 'Classic Rock 109' });
assert.deepEqual(nextTuneStatus({ kind: 'idle' }, { type: 'playing' }), { kind: 'idle' });
assert.deepEqual(nextTuneStatus({ kind: 'tuning', label: 'A' }, { type: 'error' }), { kind: 'error', label: 'A' });
assert.deepEqual(nextTuneStatus({ kind: 'idle' }, { type: 'error' }), { kind: 'idle' });
assert.deepEqual(nextTuneStatus({ kind: 'playing', label: 'A' }, { type: 'error' }), { kind: 'playing', label: 'A' });
assert.deepEqual(nextTuneStatus({ kind: 'tuning', label: 'B' }, { type: 'slow' }), { kind: 'slow', label: 'B' });
assert.deepEqual(nextTuneStatus({ kind: 'playing', label: 'B' }, { type: 'slow' }), { kind: 'playing', label: 'B' });
assert.deepEqual(nextTuneStatus({ kind: 'slow', label: 'C' }, { type: 'playing' }), { kind: 'playing', label: 'C' });
assert.deepEqual(nextTuneStatus({ kind: 'error', label: 'C' }, { type: 'tune', label: 'D' }), { kind: 'tuning', label: 'D' });
const states: TuneStatus[] = [{ kind: 'idle' }, { kind: 'tuning', label: 'X' }, { kind: 'slow', label: 'X' }, { kind: 'playing', label: 'X' }, { kind: 'error', label: 'X' }];
for (const st of states) assert.deepEqual(nextTuneStatus(st, { type: 'dismiss' }), { kind: 'idle' });
const toastSrc = fs.readFileSync('src/components/TuneStatusToast.tsx', 'utf-8');
const statusSrc = fs.readFileSync('src/utils/tuneStatus.ts', 'utf-8');
for (const [n, s] of [['toast', toastSrc], ['status', statusSrc]] as const) for (const bad of ['Math.random', 'Math.sin', 'Tuned']) assert.ok(!s.includes(bad), `${bad} in ${n}`);
console.log('[tune-status] PASS');
