import assert from 'node:assert/strict';
import { readRecentStations, recordRecentStation, RADIO_RECENT_KEY, RADIO_RECENT_MAX } from './src/utils/radioRecent';
const mem = () => { const m = new Map<string, string>(); return { getItem: (k: string) => m.get(k) ?? null, setItem: (k: string, v: string) => { m.set(k, v); }, m }; };
const st = (n: number) => ({ channelId: `radio:${n}`, src: `https://s/${n}`, title: `S${n}` });
const s = mem();
assert.deepEqual(readRecentStations(s), []);
recordRecentStation(st(1), s); recordRecentStation(st(2), s); recordRecentStation(st(1), s);
assert.deepEqual(readRecentStations(s).map((r) => r.channelId), ['radio:1', 'radio:2'], 'newest first, no duplicates');
for (let i = 3; i < 20; i++) recordRecentStation(st(i), s);
assert.equal(readRecentStations(s).length, RADIO_RECENT_MAX, 'capped');
recordRecentStation({ channelId: 'cnn', src: 'x', title: 'CNN' }, s);
assert.ok(!readRecentStations(s).some((r) => r.channelId === 'cnn'), 'non-radio ignored');
s.setItem(RADIO_RECENT_KEY, '{not json'); assert.deepEqual(readRecentStations(s), [], 'corrupt storage is safe');
s.setItem(RADIO_RECENT_KEY, JSON.stringify([{ channelId: 'radio:9' }, st(4)])); assert.equal(readRecentStations(s).length, 1, 'bad rows skipped');
const broken = { getItem() { throw new Error('blocked'); }, setItem() { throw new Error('blocked'); } };
assert.deepEqual(readRecentStations(broken), []); assert.doesNotThrow(() => recordRecentStation(st(1), broken));
console.log('[radio-recent] PASS');
