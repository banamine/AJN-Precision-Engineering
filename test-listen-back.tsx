import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { ListenBackDeckView, pageSlice, lastPage } from './src/components/ListenBackDeck';
import type { RadioEntry } from './src/utils/ajnRadioCatalog';
const mk = (i: number, video: boolean): RadioEntry => ({ id: `e${i}`, title: `Hour ${i}`, audioUrl: `https://x.test/${i}.mp3`, videoUrl: video ? `https://x.test/${i}.mp4` : null, matchReason: video ? 'file-key' : 'none', channel: 'ajn-radio', airDate: `2026-11-0${(i % 9) + 1}`, hourNumber: i, needsReview: false, classified: {} as never });
const entries = Array.from({ length: 10 }, (_, i) => mk(i, i % 2 === 0));
assert.equal(pageSlice(entries, 1).length, 4); assert.equal(lastPage(10), 1); assert.equal(lastPage(0), 0);
const noop = (): void => {};
const html = renderToStaticMarkup(<ListenBackDeckView entries={entries} error={null} videoOnly={false} page={0} playingBase="e1" onToggleVideo={noop} onPage={noop} onPlay={noop} />);
assert.match(html, /10 archived hours · 5 with video/); assert.match(html, /aria-current="true"/); assert.equal((html.match(/VIDEO<\/span>/g) ?? []).length, 3); assert.match(html, /ck-key/);
const v = renderToStaticMarkup(<ListenBackDeckView entries={entries} error={null} videoOnly page={0} playingBase={null} onToggleVideo={noop} onPage={noop} onPlay={noop} />);
assert.equal((v.match(/data-testid="listen-back-row"/g) ?? []).length, 5);
assert.match(renderToStaticMarkup(<ListenBackDeckView entries={null} error="boom" videoOnly={false} page={0} playingBase={null} onToggleVideo={noop} onPage={noop} onPlay={noop} />), /Archives unavailable \(boom\)/);
console.log('listen-back ok');
import { ScheduleDeck, GENRE_KEYS_MAX } from './src/components/ScheduleDeck';
const deck = renderToStaticMarkup(<ScheduleDeck bank="music" onPlayProgram={noop} />);
const keys = (deck.match(/data-testid="schedule-genre-key"/g) ?? []).length;
assert.ok(keys > 1 && keys <= GENRE_KEYS_MAX, `genre keys from real pools: ${keys}`);
console.log('genre keys ok');
import { SourcePrism3D } from './src/components/SourcePrism3D';
const prism = renderToStaticMarkup(<SourcePrism3D activeSource="listenback" onSelectSource={noop} />);
assert.match(prism, /data-testid="radio-mode-listenback"/); assert.match(prism, /4\. LISTEN BACK/); assert.match(prism, /rotateY\(270deg\)/);
assert.equal((prism.match(/role="tabpanel"/g) ?? []).length, 4);
console.log('prism 4 faces ok');
